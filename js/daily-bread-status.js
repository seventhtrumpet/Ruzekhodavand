/* Fresh Bread share: original square image + WhatsApp website link preview + verse caption.
   The website preview is generated by WhatsApp from the shared URL and the site's Open Graph tags.
   The preview is NOT drawn into the photo. */
(function () {
  'use strict';

  var SITE = 'https://seventhtrumpet.org/';
  var PHOTO = 'https://iili.io/n8MSJBp.jpg';
  var BUTTON_ID = 'daily-status-share-card';

  function language() {
    try { return localStorage.getItem('cog_lang') || document.documentElement.lang || 'fa'; }
    catch (e) { return document.documentElement.lang || 'fa'; }
  }
  function isEn() { return language() === 'en'; }
  function msg(en, fa) { return isEn() ? en : fa; }

  function verseData() {
    var textEl = document.getElementById('verse-text');
    var refEl = document.getElementById('verse-ref');
    var text = (textEl && textEl.textContent || '').trim();
    var ref = (refEl && refEl.textContent || '').trim();
    var verses = window.DAILY_VERSES || [];

    if (verses.length) {
      var match = null;
      for (var i = 0; i < verses.length; i++) {
        var v = verses[i];
        var refs = [v.ref_fa, v.ref_en, v.refFa, v.refEn, v.ref];
        var texts = [v.fa, v.en];
        var refHit = ref && refs.some(function (r) { return r && String(r).trim() === ref; });
        var textHit = text && texts.some(function (t) { return t && String(t).trim() === text; });
        if (refHit || textHit) { match = v; break; }
      }
      if (!match) {
        var now = new Date();
        var start = new Date(now.getFullYear(), 0, 0);
        var day = Math.floor((now - start) / 86400000);
        match = verses[Math.abs(now.getFullYear() * 366 + day) % verses.length];
      }
      if (match) {
        text = isEn() ? (match.en || match.fa || text) : (match.fa || match.en || text);
        ref = isEn()
          ? (match.ref_en || match.refEn || match.ref || ref)
          : (match.ref_fa || match.refFa || match.ref || ref);
      }
    }
    return { text: text, reference: ref };
  }

  /* URL is deliberately included in the share text so WhatsApp can create
     its native, tappable website preview from index.html Open Graph metadata. */
  function buildCaption(data) {
    return [
      data.text,
      data.reference,
      'Seventh Trumpet | شیپور هفتم',
      SITE
    ].filter(Boolean).join('\n\n');
  }

  function fetchOriginalPhoto() {
    return fetch(PHOTO, { mode: 'cors', cache: 'force-cache' })
      .then(function (response) {
        if (!response.ok) throw new Error('Photo download failed');
        return response.blob();
      })
      .then(function (blob) {
        var type = blob.type && blob.type.indexOf('image/') === 0 ? blob.type : 'image/jpeg';
        return new File([blob], 'seventh-trumpet.jpg', { type: type });
      });
  }

  function shareFreshBread() {
    var data = verseData();
    if (!data.text) {
      alert(msg('The daily verse is not ready yet. Please try again.',
        'آیه امروز هنوز آماده نیست. لطفاً دوباره تلاش کنید.'));
      return;
    }
    var caption = buildCaption(data);

    function share(file) {
      if (!navigator.share) {
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(caption);
        }
        alert(msg('Your photo and verse are ready to share. Please use your phone share menu.',
          'عکس و آیه آماده اشتراک‌گذاری است. لطفاً از منوی اشتراک‌گذاری گوشی استفاده کنید.'));
        return;
      }

      var payload = { title: 'Seventh Trumpet | شیپور هفتم', text: caption };
      if (file && navigator.canShare) {
        try {
          if (navigator.canShare({ files: [file] })) payload.files = [file];
        } catch (e) {}
      }

      navigator.share(payload).catch(function (err) {
        if (err && err.name === 'AbortError') return;
        navigator.share({ title: payload.title, text: caption }).catch(function () {});
      });
    }

    fetchOriginalPhoto().then(share).catch(function (error) {
      console.warn('Could not attach original share photo:', error);
      share(null);
    });
  }

  function addButton() {
    var section = document.getElementById('daily-verse');
    var refresh = document.getElementById('verse-refresh');
    if (!section || !refresh) return;

    ['daily-status-share-card', 'daily-share', 'daily-status-share', 'daily-status-share-image'].forEach(function (id) {
      var el = document.getElementById(id);
      if (el) try { el.remove(); } catch (e) {}
    });

    var button = document.createElement('button');
    button.type = 'button';
    button.id = BUTTON_ID;
    button.className = 'verse-refresh';
    button.style.marginInlineStart = '0.45rem';
    button.style.marginTop = '0.4rem';
    button.textContent = msg('Share', 'اشتراک');
    button.setAttribute('aria-label', msg(
      'Share original photo with tappable website preview and Bible verse',
      'اشتراک عکس اصلی همراه پیش‌نمایش لینک قابل لمس و آیه کتاب مقدس'
    ));
    button.addEventListener('click', function (event) {
      event.preventDefault();
      shareFreshBread();
    });
    refresh.parentNode.insertBefore(button, refresh.nextSibling);
  }

  function boot() { addButton(); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
})();
